import SwiftUI

public extension Color {

    // MARK: - Background
    static let backgroundPrimary = Color("backgroundPrimary", bundle: .module)
    static let backgroundSecondary = Color("backgroundSecondary", bundle: .module)
    static let backgroundTertiary = Color("backgroundTertiary", bundle: .module)

    // MARK: - Border
    static let borderPrimary = Color("borderPrimary", bundle: .module)
    static let borderSecondary = Color("borderSecondary", bundle: .module)
    static let borderTertiary = Color("borderTertiary", bundle: .module)

    // MARK: - Button
    static let buttonPrimary = Color("buttonPrimary", bundle: .module)
    static let buttonSecondary = Color("buttonSecondary", bundle: .module)
    static let buttonTertiary = Color("buttonTertiary", bundle: .module)

    // MARK: - Foreground
    static let foregroundPrimary = Color("foregroundPrimary", bundle: .module)
    static let foregroundSecondary = Color("foregroundSecondary", bundle: .module)
    static let foregroundTertiary = Color("foregroundTertiary", bundle: .module)

    // MARK: - Shadow
    static let shadowPrimary = Color("shadowPrimary", bundle: .module)
    static let shadowSecondary = Color("shadowSecondary", bundle: .module)
    static let shadowTertiary = Color("shadowTertiary", bundle: .module)

    // MARK: - Text
    static let textPrimary = Color("textPrimary", bundle: .module)
    static let textSecondary = Color("textSecondary", bundle: .module)
    static let textTertiary = Color("textTertiary", bundle: .module)
}
